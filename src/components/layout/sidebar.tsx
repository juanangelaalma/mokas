'use client';

import Link from 'next/link';
import { usePathname } from 'next/navigation';
import { cn } from '@/lib/utils';

const navigation = [
  { name: 'Dashboard', href: '/dashboard', icon: HomeIcon },
  { name: 'Transaksi', href: '/dashboard/transactions', icon: TransactionIcon },
  { name: 'Akun', href: '/dashboard/accounts', icon: AccountIcon },
  { name: 'Kontak', href: '/dashboard/contacts', icon: ContactIcon },
  {
    name: 'Laporan',
    icon: ReportIcon,
    children: [
      { name: 'Jurnal Umum', href: '/dashboard/reports/journal' },
      { name: 'Buku Besar', href: '/dashboard/reports/ledger' },
      { name: 'Neraca Saldo', href: '/dashboard/reports/trial-balance' },
      { name: 'Laba Rugi', href: '/dashboard/reports/profit-loss' },
      { name: 'Neraca', href: '/dashboard/reports/balance-sheet' },
    ],
  },
];

export function Sidebar() {
  const pathname = usePathname();

  return (
    <aside className="w-64 bg-white border-r border-gray-200 min-h-screen">
      <div className="p-6 border-b">
        <Link href="/dashboard" className="text-2xl font-bold text-primary-600">
          Mokas
        </Link>
      </div>
      <nav className="p-4 space-y-1">
        {navigation.map((item) => {
          if (item.children) {
            return (
              <div key={item.name} className="space-y-1">
                <div className="flex items-center px-3 py-2 text-sm font-medium text-gray-600">
                  <item.icon className="w-5 h-5 mr-3" />
                  {item.name}
                </div>
                <div className="ml-8 space-y-1">
                  {item.children.map((child) => (
                    <Link
                      key={child.href}
                      href={child.href}
                      className={cn(
                        'block px-3 py-2 text-sm rounded-lg transition-colors',
                        pathname === child.href
                          ? 'bg-primary-50 text-primary-700 font-medium'
                          : 'text-gray-600 hover:bg-gray-100'
                      )}
                    >
                      {child.name}
                    </Link>
                  ))}
                </div>
              </div>
            );
          }

          return (
            <Link
              key={item.href}
              href={item.href!}
              className={cn(
                'flex items-center px-3 py-2 text-sm font-medium rounded-lg transition-colors',
                pathname === item.href
                  ? 'bg-primary-50 text-primary-700'
                  : 'text-gray-600 hover:bg-gray-100'
              )}
            >
              <item.icon className="w-5 h-5 mr-3" />
              {item.name}
            </Link>
          );
        })}
      </nav>
    </aside>
  );
}

